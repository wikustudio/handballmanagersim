export function getLocalAssetPath(clubId: number | string): string {
  const numId = Number(clubId);
  const ext = LOCAL_EXTENSIONS[numId] || (LOCAL_EXTENSIONS as any)[String(clubId)] || "svg";
  return `${LOCAL_ASSET_CACHE_PATH}/club_${numId}.${ext}`;
}

export function getFallbackMirror(club: { id: number }): string {
  const directWeb = REAL_WORLD_LOGOS[club.id];
  if (directWeb) {
    const clean = directWeb.replace(/^https?:\/\//, "");
    return `https://images.weserv.nl/?url=${encodeURIComponent(clean)}&w=160&output=png`;
  }
  return getLocalAssetPath(club.id);
}

